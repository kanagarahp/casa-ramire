function attrString(attributes = {}) {
  return Object.entries(attributes)
    .map(([key, value]) => `${key}="${String(value).replace(/"/g, '&quot;')}"`)
    .join(' ');
}

/**
 * Render an icon as an inline SVG string.
 * @param {keyof typeof ICONS} name
 * @param {string} className Tailwind classes (default 5x5)
 */
export function icon(name, className = 'w-5 h-5', strokeWidth = 2) {
  const node = ICONS[name];
  if (!node) return '';
  const body = node.map(([tag, attributes]) => `<${tag} ${attrString(attributes)} />`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" class="${className}" aria-hidden="true" focusable="false">${body}</svg>`;
}

